#!/usr/bin/env python3
"""Vendor, render, verify and fetch the pinned impeccable UI/UX skill.

MADFAM's standing rule: every UI/UX task uses impeccable
(https://github.com/pbakaus/impeccable, Apache-2.0). Selva pins one release:

* ``packages/skills/vendor/impeccable/`` -- verbatim upstream files (skill text,
  command references, LICENSE, NOTICE). Never hand-edit; re-run ``sync``.
* ``packages/skills/vendor/impeccable.pin.json`` -- the pin: tag, commit, npm
  and engine versions, the npm ``sha512`` integrity of each engine binary
  package, and the sha256 of every vendored file.
* ``packages/skills/vendor/impeccable.adapter.md`` -- the Selva-authored
  harness adapter (how the upstream skill maps onto Selva workers).
* ``packages/skills/skill-definitions/impeccable/SKILL.md`` -- GENERATED from
  the three above; the registry loads it on every UI/UX task.

Subcommands (stdlib only, so the Docker builder can run it before ``uv sync``):

    # Update the pin from a checkout of the upstream tag (network: npm registry)
    git clone --depth 1 --branch skill-v4.7.0 https://github.com/pbakaus/impeccable /tmp/imp
    python3 scripts/vendor-impeccable.py sync --source /tmp/imp --npm-version 4.7.0

    python3 scripts/vendor-impeccable.py render   # regenerate SKILL.md (no network)
    python3 scripts/vendor-impeccable.py check    # CI drift + tamper check (no network)

    # Download + verify the pinned engine binary (Dockerfile.workers, local dev)
    python3 scripts/vendor-impeccable.py fetch-engine --dest /opt/impeccable/bin
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import io
import json
import platform
import shutil
import subprocess
import sys
import tarfile
import urllib.request
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
VENDOR_ROOT = ROOT / "packages" / "skills" / "vendor"
VENDOR_DIR = VENDOR_ROOT / "impeccable"
PIN_PATH = VENDOR_ROOT / "impeccable.pin.json"
ADAPTER_PATH = VENDOR_ROOT / "impeccable.adapter.md"
SKILL_MD_PATH = ROOT / "packages" / "skills" / "skill-definitions" / "impeccable" / "SKILL.md"

UPSTREAM_REPO = "https://github.com/pbakaus/impeccable"
# The upstream build emits one copy of the skill per agent harness; the
# `.agents/` copy is the cross-harness (AgentSkills) one.
UPSTREAM_SKILL_DIR = ".agents/skills/impeccable"
# Files copied from UPSTREAM_SKILL_DIR. The launcher, live-mode browser
# bundles, font index and Codex sub-agent TOMLs are not used by Selva workers
# and are deliberately left out.
SKILL_FILES = ("SKILL.md", "scripts/VERSION", "scripts/command-metadata.json")
SKILL_DIRS = ("reference",)
# Files copied from the upstream repo root (license obligations).
ROOT_FILES = ("LICENSE", "NOTICE.md")
ENGINE_TARGETS = ("linux-x64", "linux-arm64", "darwin-x64", "darwin-arm64")
NPM_REGISTRY = "https://registry.npmjs.org"

GENERATED_MARKER = "<!-- GENERATED by scripts/vendor-impeccable.py -- do not edit by hand. -->"


# -- helpers -------------------------------------------------------------------


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _vendored_files() -> list[Path]:
    return sorted(p for p in VENDOR_DIR.rglob("*") if p.is_file())


def _split_frontmatter(text: str) -> tuple[str, str]:
    if not text.startswith("---"):
        raise ValueError("upstream SKILL.md has no YAML frontmatter")
    parts = text.split("---", 2)
    if len(parts) < 3:
        raise ValueError("upstream SKILL.md frontmatter is not closed")
    return parts[1], parts[2].strip()


def load_pin() -> dict[str, Any]:
    pin: dict[str, Any] = json.loads(PIN_PATH.read_text(encoding="utf-8"))
    return pin


# -- render --------------------------------------------------------------------


def render_skill_md(pin: dict[str, Any] | None = None) -> str:
    """Return the generated Selva SKILL.md text (deterministic, no network)."""
    pin = pin or load_pin()
    _, upstream_body = _split_frontmatter((VENDOR_DIR / "SKILL.md").read_text(encoding="utf-8"))
    craft_floor = (VENDOR_DIR / "reference" / "craft-floor.md").read_text(encoding="utf-8").strip()
    commands = json.loads(
        (VENDOR_DIR / "scripts" / "command-metadata.json").read_text(encoding="utf-8")
    )
    adapter = ADAPTER_PATH.read_text(encoding="utf-8").strip()
    replacements = {
        "{{npm_version}}": pin["npm_version"],
        "{{engine_version}}": pin["engine_version"],
        "{{skill_tag}}": pin["skill_tag"],
        "{{commit}}": pin["commit"],
        "{{commands}}": ", ".join(f"`{name}`" for name in commands),
        "{{command_count}}": str(len(commands)),
    }
    for token, value in replacements.items():
        adapter = adapter.replace(token, value)

    frontmatter = "\n".join(
        [
            "---",
            "name: impeccable",
            "description: >-",
            "  MADFAM standing rule: use impeccable for any and all UI/UX work. Design,",
            "  redesign, critique, audit, polish, harden, clarify or adapt a frontend",
            "  interface (pages, components, styles, forms, dashboards, empty states, UX",
            "  copy, design reviews) and run the pinned deterministic detector on every",
            "  changed UI file before completion. Not for backend-only or non-UI tasks.",
            "audience: tenant",
            "license: Apache-2.0",
            "compatibility: >-",
            f"  Vendored from pbakaus/impeccable {pin['skill_tag']} (npm",
            f"  impeccable@{pin['npm_version']}, engine {pin['engine_version']}).",
            "allowed_tools:",
            "  - file_read",
            "  - impeccable_detect",
            "metadata:",
            "  category: design",
            "  upstream: pbakaus/impeccable",
            f'  upstream_tag: "{pin["skill_tag"]}"',
            f'  upstream_commit: "{pin["commit"]}"',
            f'  upstream_version: "{pin["npm_version"]}"',
            f'  engine_version: "{pin["engine_version"]}"',
            "  generated_by: scripts/vendor-impeccable.py",
            "---",
        ]
    )
    notice = (
        f"{GENERATED_MARKER}\n"
        "<!-- Sources: packages/skills/vendor/impeccable.adapter.md (Selva) plus the verbatim\n"
        f"     upstream SKILL.md body and reference/craft-floor.md of pbakaus/impeccable\n"
        f"     {pin['skill_tag']} ({pin['commit']}), Copyright Paul Bakaus, Apache-2.0.\n"
        "     Full license and notices: packages/skills/vendor/impeccable/LICENSE, NOTICE.md. -->"
    )
    sections = [
        frontmatter,
        "",
        notice,
        "",
        adapter,
        "",
        f"## Upstream skill: impeccable {pin['npm_version']} (verbatim)",
        "",
        upstream_body,
        "",
        "## Upstream reference: craft-floor.md (verbatim)",
        "",
        craft_floor,
        "",
    ]
    return "\n".join(sections)


def cmd_render(_: argparse.Namespace) -> int:
    SKILL_MD_PATH.parent.mkdir(parents=True, exist_ok=True)
    SKILL_MD_PATH.write_text(render_skill_md(), encoding="utf-8")
    print(f"wrote {SKILL_MD_PATH.relative_to(ROOT)}")
    return 0


# -- check ---------------------------------------------------------------------


def check_problems() -> list[str]:
    """Return drift/tamper problems; empty when the vendored tree is consistent."""
    problems: list[str] = []
    pin = load_pin()
    expected: dict[str, str] = pin["files"]
    actual = {str(p.relative_to(VENDOR_DIR)): _sha256(p) for p in _vendored_files()}
    for rel in sorted(set(expected) - set(actual)):
        problems.append(f"vendored file missing: {rel}")
    for rel in sorted(set(actual) - set(expected)):
        problems.append(f"unpinned file in vendor dir: {rel}")
    for rel in sorted(set(expected) & set(actual)):
        if expected[rel] != actual[rel]:
            problems.append(f"vendored file changed by hand (sha256 mismatch): {rel}")
    version_file = (VENDOR_DIR / "scripts" / "VERSION").read_text(encoding="utf-8").strip()
    if version_file != pin["engine_version"]:
        problems.append(f"engine VERSION {version_file} != pin engine_version")
    missing_targets = [t for t in ENGINE_TARGETS if t not in pin.get("engine_packages", {})]
    if missing_targets:
        problems.append(f"pin lacks engine integrity for: {', '.join(missing_targets)}")
    rerun = "run: python3 scripts/vendor-impeccable.py render"
    if not SKILL_MD_PATH.is_file():
        problems.append(f"generated SKILL.md missing; {rerun}")
    elif SKILL_MD_PATH.read_text(encoding="utf-8") != render_skill_md(pin):
        problems.append(f"generated SKILL.md is stale; {rerun}")
    return problems


def cmd_check(_: argparse.Namespace) -> int:
    problems = check_problems()
    for problem in problems:
        print(f"impeccable vendor: {problem}", file=sys.stderr)
    if not problems:
        print("impeccable vendor: OK")
    return 1 if problems else 0


# -- sync ----------------------------------------------------------------------


def _npm_integrity(package: str, version: str) -> str:
    url = f"{NPM_REGISTRY}/{package.replace('/', '%2F')}/{version}"
    with urllib.request.urlopen(url, timeout=30) as resp:  # noqa: S310 -- fixed https host
        meta = json.loads(resp.read())
    integrity: str = meta["dist"]["integrity"]
    return integrity


def _npm_engine_version(npm_version: str) -> str:
    url = f"{NPM_REGISTRY}/impeccable/{npm_version}"
    with urllib.request.urlopen(url, timeout=30) as resp:  # noqa: S310 -- fixed https host
        meta = json.loads(resp.read())
    versions = set(meta.get("optionalDependencies", {}).values())
    if len(versions) != 1:
        raise SystemExit(f"impeccable@{npm_version} pins several engine versions: {versions}")
    return versions.pop()


def cmd_sync(args: argparse.Namespace) -> int:
    source = Path(args.source).resolve()
    skill_tag = f"skill-v{args.npm_version}"
    commit = subprocess.run(
        ["git", "-C", str(source), "rev-parse", "HEAD"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    tag_commit = subprocess.run(
        ["git", "-C", str(source), "rev-list", "-n", "1", skill_tag],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    if commit != tag_commit:
        raise SystemExit(f"{source} is at {commit}, not at {skill_tag} ({tag_commit})")

    skill_src = source / UPSTREAM_SKILL_DIR
    engine_version = (skill_src / "scripts" / "VERSION").read_text(encoding="utf-8").strip()
    npm_engine = _npm_engine_version(args.npm_version)
    if npm_engine != engine_version:
        raise SystemExit(
            f"{skill_tag} skill pins engine {engine_version} but npm "
            f"impeccable@{args.npm_version} pins {npm_engine}"
        )

    if VENDOR_DIR.exists():
        shutil.rmtree(VENDOR_DIR)
    VENDOR_DIR.mkdir(parents=True)
    for rel in SKILL_FILES:
        (VENDOR_DIR / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(skill_src / rel, VENDOR_DIR / rel)
    for rel in SKILL_DIRS:
        shutil.copytree(skill_src / rel, VENDOR_DIR / rel)
    for rel in ROOT_FILES:
        shutil.copy2(source / rel, VENDOR_DIR / rel)

    pin = {
        "upstream": UPSTREAM_REPO,
        "license": "Apache-2.0",
        "skill_tag": skill_tag,
        "commit": commit,
        "skill_source": UPSTREAM_SKILL_DIR,
        "npm_package": "impeccable",
        "npm_version": args.npm_version,
        "engine_version": engine_version,
        "engine_packages": {
            target: {
                "package": f"@impeccable/cli-{target}",
                "integrity": _npm_integrity(f"@impeccable/cli-{target}", engine_version),
            }
            for target in ENGINE_TARGETS
        },
        "files": {str(p.relative_to(VENDOR_DIR)): _sha256(p) for p in _vendored_files()},
    }
    PIN_PATH.write_text(json.dumps(pin, indent=2) + "\n", encoding="utf-8")
    print(f"pinned impeccable {skill_tag} ({commit}), engine {engine_version}")
    return cmd_render(args)


# -- fetch-engine --------------------------------------------------------------


def _host_target() -> str:
    os_name = {"Linux": "linux", "Darwin": "darwin"}.get(platform.system())
    arch = {"x86_64": "x64", "amd64": "x64", "aarch64": "arm64", "arm64": "arm64"}.get(
        platform.machine().lower()
    )
    if not os_name or not arch:
        raise SystemExit(f"no impeccable engine for {platform.system()}/{platform.machine()}")
    return f"{os_name}-{arch}"


def cmd_fetch_engine(args: argparse.Namespace) -> int:
    pin = load_pin()
    target = args.target or _host_target()
    entry = pin["engine_packages"].get(target)
    if entry is None:
        raise SystemExit(f"pin has no engine package for {target}")
    package, version = entry["package"], pin["engine_version"]
    name = package.split("/", 1)[1]
    url = f"{NPM_REGISTRY}/{package}/-/{name}-{version}.tgz"
    with urllib.request.urlopen(url, timeout=120) as resp:  # noqa: S310 -- fixed https host
        blob = resp.read()
    algo, _, expected_b64 = entry["integrity"].partition("-")
    if algo != "sha512":
        raise SystemExit(f"unsupported integrity algorithm {algo}")
    actual_b64 = base64.b64encode(hashlib.sha512(blob).digest()).decode()
    if actual_b64 != expected_b64:
        raise SystemExit(f"integrity mismatch for {url}; refusing the download")
    with tarfile.open(fileobj=io.BytesIO(blob), mode="r:gz") as tar:
        member = tar.getmember("package/bin/impeccable")
        extracted = tar.extractfile(member)
        if extracted is None:
            raise SystemExit("engine tarball has no package/bin/impeccable")
        data = extracted.read()
    dest = Path(args.dest)
    dest.mkdir(parents=True, exist_ok=True)
    binary = dest / "impeccable"
    binary.write_bytes(data)
    binary.chmod(0o755)
    print(f"installed impeccable engine {version} ({target}) at {binary}")
    return 0


# -- main ----------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)

    sync = sub.add_parser("sync", help="re-vendor from an upstream checkout at skill-v<npm>")
    sync.add_argument("--source", required=True, help="path to a pbakaus/impeccable checkout")
    sync.add_argument("--npm-version", required=True, help="npm impeccable version, e.g. 4.7.0")
    sync.set_defaults(func=cmd_sync)

    sub.add_parser("render", help="regenerate SKILL.md").set_defaults(func=cmd_render)
    sub.add_parser("check", help="verify vendor tree + SKILL.md").set_defaults(func=cmd_check)

    fetch = sub.add_parser("fetch-engine", help="download + verify the pinned engine binary")
    fetch.add_argument("--dest", required=True, help="directory to install `impeccable` into")
    fetch.add_argument("--target", choices=ENGINE_TARGETS, help="default: this machine")
    fetch.set_defaults(func=cmd_fetch_engine)

    args = parser.parse_args(argv)
    result: int = args.func(args)
    return result


if __name__ == "__main__":
    sys.exit(main())
